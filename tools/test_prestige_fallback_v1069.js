const fs=require('fs'),vm=require('vm'),assert=require('assert');
const src=fs.readFileSync(process.argv[2]||'app/src/main/assets/pomagier.user.js','utf8');
const start=src.indexOf('  function prestigeAutoChoose(candidates){');
const end=src.indexOf('\n  function prestigeAutoBusyElsewhere(){',start);
assert(start>0&&end>start,'selection helper missing');
const context={};vm.createContext(context);vm.runInContext(src.slice(start,end),context);
const choose=context.prestigeAutoChoose;
const a=(id,level,eligible=false,expectedGain=8)=>({id,level,history:{eligible,wins:eligible?4:0},expectedGain});
let x=choose([a(10,40),a(20,75,true),a(30,3)]);
assert.equal(x.choice.id,20,'qualified opponent has priority');assert.equal(x.rule,'history');
x=choose([a(10,40),a(20,75),a(30,3)]);
assert.equal(x.choice.id,30,'fallback picks smallest level');assert.equal(x.rule,'lowest_level');
x=choose([a(20,9),a(10,9),a(25,15)]);assert.equal(x.choice.id,10,'tie uses smaller ID');
x=choose([a(20,0),a(10,null),a(25,15)]);assert.equal(x.choice.id,25,'unknown level excluded');
assert.equal(choose([a(20,0),a(10,null)]).choice,null,'unknown-only list gives no attack');
assert.equal(choose([]).choice,null,'empty list gives no attack');
assert(src.includes('const selection=prestigeAutoChoose(candidates);'),'cycle uses helper');
assert(src.includes('const pointState=prestigeAutoStatusCheck(status);'),'points check still active');
assert(src.includes('prestigeAuto.calibration.ownId!==pvpLabOwnId()'),'account guard still active');
assert(src.includes("if(!result.won)prestigeAuto.enabled=false;"),'stop after loss still active');
console.log('PASS v1.0.69 prestige fallback: priority, lowest level, missing levels, safety guards');
